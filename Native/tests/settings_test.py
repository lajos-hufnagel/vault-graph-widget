from pathlib import Path
import tempfile, subprocess
workspace = tempfile.TemporaryDirectory(prefix='vaultgraph-settings-')
root=Path(workspace.name)/'fixture';(root/'.obsidian').mkdir(parents=True,exist_ok=True)
(root/'concepts').mkdir(exist_ok=True);(root/'_raw').mkdir(exist_ok=True)
(root/'concepts/A.md').write_text('---\ntags: [test, privat]\n---\n[[B]] [[Missing]] ![[photo.png]] [relative](B.md) #inline\n')
(root/'concepts/B.md').write_text('[[A]]')
(root/'_raw/Hidden.md').write_text('[[A]] [[OnlyHidden]] #onlyHidden')
(root/'Orphan.md').write_text('alone')
(root/'photo.png').write_bytes(b'fixture')
s=(Path(__file__).resolve().parents[1]/'Graph.swift').read_text().split('func nodeColor',1)[0]
s+='''
let fixture = URL(fileURLWithPath: "/private/tmp/vaultgraph-settings-fixture")
func config(_ tags: Bool = false, _ attachments: Bool = false, _ unresolved: Bool = false, _ orphans: Bool = true) throws {
    let object: [String: Any] = ["search": "-path:\\"_raw/\\"", "showTags": tags, "showAttachments": attachments, "hideUnresolved": !unresolved, "showOrphans": orphans, "nodeSizeMultiplier": 2, "lineSizeMultiplier": 3, "repelStrength": 5, "linkDistance": 80, "colorGroups": [["query": "path:\\"concepts/\\"", "color": ["rgb": 123456, "a": 0.5]], ["query":"file:/.*/", "color": ["rgb": 654321,"a":1]]]]
    try JSONSerialization.data(withJSONObject:object).write(to:fixture.appendingPathComponent(".obsidian/graph.json"))
}
try config()
let filtered = try GraphStore.scan(fixture, useObsidianFilter:true)
assert(filtered.nodes.count == 3)
assert(filtered.nodes.first { $0.name == "A" }?.rgb == 123456)
assert(filtered.nodes.first { $0.name == "A" }?.alpha == 0.5)
assert(filtered.settings?.nodeSizeMultiplier == 2)
assert(filtered.settings?.lineSizeMultiplier == 3)
let full = try GraphStore.scan(fixture, useObsidianFilter:false)
assert(full.nodes.count == 6)
assert(full.nodes.contains { $0.id == "Missing" })
assert(full.nodes.first { $0.name == "A" }?.rgb == 123456)
try config(true,true,true,false)
let expanded = try GraphStore.scan(fixture,useObsidianFilter:true)
assert(expanded.nodes.contains { $0.kind == "tag" && $0.id == "#test" })
assert(expanded.nodes.contains { $0.kind == "attachment" && $0.id == "photo.png" })
assert(expanded.nodes.contains { $0.kind == "unresolved" && $0.id == "Missing" })
assert(!expanded.nodes.contains { $0.name == "Orphan" })
assert(!expanded.nodes.contains { $0.id == "#onlyHidden" || $0.id == "OnlyHidden" })
assert(expanded.edges.allSatisfy { expanded.nodes.indices.contains($0.a) && expanded.nodes.indices.contains($0.b) })
let defaults = try GraphStore.scan(fixture,useObsidianFilter:false)
assert(defaults.settings?.search == "")
assert(defaults.settings?.showTags == false)
assert(defaults.settings?.showAttachments == false)
assert(defaults.settings?.hideUnresolved == false)
assert(defaults.settings?.showOrphans == true)
assert(!defaults.nodes.contains { $0.kind == "tag" || $0.kind == "attachment" })
assert(defaults.nodes.contains { $0.kind == "unresolved" })
assert(defaults.nodes.contains { $0.name == "Orphan" })
assert(defaults.nodes.contains { $0.name == "Hidden" })
assert(defaults.nodes.first { $0.name == "A" }?.rgb == expanded.nodes.first { $0.name == "A" }?.rgb)
assert(defaults.nodes.first { $0.name == "A" }?.alpha == expanded.nodes.first { $0.name == "A" }?.alpha)
let saved = try JSONDecoder().decode(ObsidianGraphFilter.self,from:Data(contentsOf:fixture.appendingPathComponent(".obsidian/graph.json")))
assert(saved.showTags == true && saved.showAttachments == true && saved.showOrphans == false)
let roundtrip = try JSONDecoder().decode(GraphSnapshot.self, from:JSONEncoder().encode(expanded))
assert(roundtrip.settings?.colorGroups?.count == 2)
print("PASS: colors + priority + alpha, filters, settings, tags, attachments, unresolved links, orphans, edge remapping, snapshot roundtrip, default filter mode and preserved vault config")
'''
s=s.replace('/private/tmp/vaultgraph-settings-fixture', str(root))
script=Path(workspace.name)/'settings.swift'
script.write_text(s)
subprocess.run(['swift','-module-cache-path',str(Path(workspace.name)/'module-cache'),str(script)],check=True)
